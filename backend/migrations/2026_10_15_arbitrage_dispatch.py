"""Prepare the arbitrage decision tables for API bulk loads (battery_master, BESS_Arbitrage_DataPack).

    python 2026_10_15_arbitrage_dispatch.py            # rehearsal: apply, verify, ROLLBACK
    python 2026_10_15_arbitrage_dispatch.py --commit   # for real

1. as_award has only a generated award_id, so re-uploading as_award.csv would duplicate every award. Add a natural
   key (system_id, product_id, delivery_start) so the bulk load can update instead.
2. optimization_run.run_id is GENERATED ALWAYS, but optimization_run.csv carries the run ids that decision_state.csv
   and dispatch_schedule.csv / dispatch_outcome.csv refer to. Switch to GENERATED BY DEFAULT so the file's ids can be
   loaded as they are; the loader re-syncs the sequence afterwards so new runs continue after the highest id.
All tables are empty when this runs.
"""
import sys

import psycopg2

from bess_common.db_settings import psycopg2_dsn  # noqa: E402  (DATABASE_URL from env / backend/.env)

DSN = psycopg2_dsn()

SQL = """
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_as_award_slot') THEN
        ALTER TABLE battery_master.as_award
            ADD CONSTRAINT uq_as_award_slot UNIQUE (system_id, product_id, delivery_start);
    END IF;
END $$;
ALTER TABLE battery_master.optimization_run ALTER COLUMN run_id SET GENERATED BY DEFAULT;
"""

CHECK = """
SELECT (SELECT pg_get_constraintdef(oid) FROM pg_constraint WHERE conname = 'uq_as_award_slot'),
       (SELECT is_identity || '/' || identity_generation FROM information_schema.columns
         WHERE table_schema = 'battery_master' AND table_name = 'optimization_run' AND column_name = 'run_id')
"""


def main(commit: bool) -> None:
    conn = psycopg2.connect(**DSN)
    try:
        with conn.cursor() as cur:
            cur.execute(SQL)
            cur.execute(CHECK)
            award_key, run_identity = cur.fetchone()
            print("as_award key:      ", award_key)
            print("run_id identity:   ", run_identity)
        if commit:
            conn.commit()
            print("committed")
        else:
            conn.rollback()
            print("rolled back (rehearsal) - pass --commit to apply")
    finally:
        conn.close()


if __name__ == "__main__":
    main("--commit" in sys.argv)
